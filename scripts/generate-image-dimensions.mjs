import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = fileURLToPath(new URL("../", import.meta.url));
const publicDir = path.join(root, "public");
const dimensions = {};
for (const file of fs.readdirSync(publicDir, { recursive: true }).filter(file => /\.(png|jpg|jpeg|webp)$/.test(file)).sort()) {
  const metadata = await sharp(path.join(publicDir, file)).metadata();
  dimensions["/" + file.replaceAll("\\", "/")] = [metadata.width, metadata.height];
}
fs.writeFileSync(path.join(root, "src/lib/image-dimensions.ts"),
  "// Generated by npm run images:dimensions. Reserves image space before loading.\n" +
  "const dimensions: Record<string, readonly [number, number]> = " + JSON.stringify(dimensions, null, 2) +
  ";\nexport function imageDimensions(src: string) { const [width, height] = dimensions[src] || [1600, 900]; return { width, height }; }\n");
